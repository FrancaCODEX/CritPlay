CREATE TABLE games (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 title VARCHAR(255) NOT NULL,genre VARCHAR(255),platforms VARCHAR(255),release_year INTEGER NOT NULL,
 steam_app_id BIGINT,description VARCHAR(2000)
);
CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username VARCHAR(30) NOT NULL UNIQUE,
 display_name VARCHAR(80) NOT NULL,password_hash VARCHAR(255) NOT NULL,role VARCHAR(20) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE diary_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT REFERENCES app_users(id),
 game_id BIGINT NOT NULL REFERENCES games(id),status VARCHAR(255) NOT NULL,
 rating INTEGER CHECK(rating IS NULL OR rating BETWEEN 1 AND 5),review VARCHAR(2000),
 favorite BOOLEAN NOT NULL,updated_at TIMESTAMP(6) WITH TIME ZONE,
 CONSTRAINT diary_user_game_unique UNIQUE(user_id,game_id)
);
