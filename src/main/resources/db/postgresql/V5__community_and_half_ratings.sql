ALTER TABLE diary_entries DROP CONSTRAINT IF EXISTS diary_entries_rating_check;
ALTER TABLE diary_entries ALTER COLUMN rating TYPE DOUBLE PRECISION USING rating::DOUBLE PRECISION;
ALTER TABLE diary_entries ADD CONSTRAINT diary_half_rating CHECK(rating IS NULL OR (rating BETWEEN 0.5 AND 5 AND rating*2=FLOOR(rating*2)));
ALTER TABLE app_users ADD COLUMN banner_url VARCHAR(255);
CREATE TABLE profile_featured_games (
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 game_id BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
 position INTEGER NOT NULL CHECK(position BETWEEN 1 AND 4),
 PRIMARY KEY(user_id,position), UNIQUE(user_id,game_id)
);
CREATE TABLE review_likes (
 entry_id BIGINT NOT NULL REFERENCES diary_entries(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(entry_id,user_id)
);
CREATE TABLE activity_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry_id BIGINT NOT NULL REFERENCES diary_entries(id) ON DELETE CASCADE,
 actor_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 game_id BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
 action VARCHAR(20) NOT NULL CHECK(action IN ('STATUS','RATING','REVIEW')),
 status VARCHAR(30), rating DOUBLE PRECISION,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX activity_actor_idx ON activity_events(actor_id,id);
CREATE INDEX activity_entry_idx ON activity_events(entry_id);
CREATE INDEX likes_user_idx ON review_likes(user_id);
